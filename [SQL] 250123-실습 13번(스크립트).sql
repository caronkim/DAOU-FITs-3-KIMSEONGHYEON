-- 9. 입사 년도별 급여 합계를 출력하고 전체 급여 합계를 출력
-- 전체 급여 합계는 가장 아랫줄에 'ALL YEARS'로 표시

SELECT NVL(TO_CHAR(HIRE_DATE, 'YYYY'), 'ALL YEARS') YEAR, SUM(SALARY) TOTAL
