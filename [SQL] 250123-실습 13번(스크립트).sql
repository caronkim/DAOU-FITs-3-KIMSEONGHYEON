-- 1. 지점별 승인된 대출의 총 금액을 계산
-- 해당 금액이 전체 지점에서 승인된 대출금액의 평균보다 낮은 지점
-- 출력 컬럼 : 지점명, 승인된 대출의 총 금액, 전체 지점에서 승인된 대출 금액의 평균
-- 평균값은 반올림하여 소수점 아래 둘째자리까지 표현

SELECT * FROM (

    SELECT (SELECT NAME FROM BRANCHES WHERE BRANCH_ID = L.BRANCH_ID) BRANCH_NAME,
        SUM(AMOUNT) TOTAL_AMOUNT,
        ROUND(AVG(SUM(AMOUNT)) OVER (), 2) AVG_TOTAL_AMOUNT
    FROM LOANS L
    WHERE STATUS = 'APPROVED'
    GROUP BY BRANCH_ID
    
)
WHERE TOTAL_AMOUNT < AVG_TOTAL_AMOUNT
ORDER BY LENGTH(BRANCH_NAME), BRANCH_NAME;


SELECT (SELECT NAME FROM BRANCHES WHERE BRANCH_ID = L.BRANCH_ID) BRANCH_NAME,
    SUM(L.AMOUNT) TOTAL_AMOUNT,
    (SELECT ROUND(AVG(SUM(AMOUNT)), 2)
    FROM LOANS
    WHERE STATUS = 'APPROVED'
    GROUP BY BRANCH_ID) AVG_TOTAL_AMOUNT
FROM LOANS L
WHERE STATUS = 'APPROVED'
GROUP BY BRANCH_ID
HAVING SUM(L.AMOUNT) < (SELECT AVG(SUM(AMOUNT))
                        FROM LOANS
                        WHERE STATUS = 'APPROVED'
                        GROUP BY BRANCH_ID)
ORDER BY LENGTH(BRANCH_NAME), BRANCH_NAME;


SELECT DISTINCT
    (SELECT B.NAME FROM BRANCHES B WHERE B.BRANCH_ID = T.BRANCH_ID) AS BRANCH_NAME,
    T.BRANCH_SUM,
    ROUND((T.ALL_AVG),2) AS ALL_AVG
FROM (
    SELECT BRANCH_ID,
        SUM(AMOUNT) OVER(PARTITION BY BRANCH_ID) AS BRANCH_SUM,
        AVG(AMOUNT) OVER() AS ALL_AVG
    FROM LOANS
    WHERE STATUS = 'APPROVED'
    ) T
WHERE T.BRANCH_SUM < T.ALL_AVG;

-- 2. 모든 직원의 사번과 이름, 상사의 이름, 상사가 속한 부서 이름 출력
-- 상사가 없는 직원은 'NO MANAGER', 상사가 속한 부서가 없으면 'NO DEPARTMENT'

SELECT E.EMPLOYEE_ID,
    E.NAME,
    NVL((SELECT NAME
        FROM EMPLOYEES
        WHERE EMPLOYEE_ID = E.MANAGER_ID), 'NO MANAGER') MANAGER_NAME,
    NVL((SELECT DEPARTMENT_NAME 
        FROM DEPARTMENTS
        WHERE DEPARTMENT_ID = (
            SELECT DEPARTMENT_ID 
            FROM EMPLOYEES 
            WHERE EMPLOYEE_ID = E.MANAGER_ID)), 'NO DEPARTMENT') MANAGER_DEPT
FROM EMPLOYEES E
START WITH E.MANAGER_ID IS NULL
CONNECT BY PRIOR E.EMPLOYEE_ID = E.MANAGER_ID;

SELECT EMPLOYEE_ID,
    NAME,
    NVL(MANAGER_NAME, 'NO MANAGER') MANAGER_NAME,
    NVL((SELECT DEPARTMENT_NAME 
        FROM DEPARTMENTS
        WHERE DEPARTMENT_ID = T.MANAGER_DEPT_ID), 'NO DEPARTMENT') MANAGER_DEPT
FROM (SELECT EMPLOYEE_ID,
        NAME,
        MANAGER_ID,
        (SELECT NAME
        FROM EMPLOYEES
        WHERE EMPLOYEE_ID = E.MANAGER_ID) MANAGER_NAME,
        (SELECT DEPARTMENT_ID 
        FROM EMPLOYEES 
        WHERE EMPLOYEE_ID = E.MANAGER_ID) MANAGER_DEPT_ID
        FROM EMPLOYEES E) T
START WITH MANAGER_ID IS NULL
CONNECT BY PRIOR EMPLOYEE_ID = MANAGER_ID;

SELECT E1.EMPLOYEE_ID,
    E1.NAME,
    NVL(E2.NAME, 'NO MANAGER') MANAGER_NAME,
    NVL((SELECT DEPARTMENT_NAME 
        FROM DEPARTMENTS
        WHERE DEPARTMENT_ID = E2.DEPARTMENT_ID), 'NO DEPARTMENT') MANAGER_DEPT
FROM EMPLOYEES E1
LEFT OUTER JOIN EMPLOYEES E2
 ON E1.MANAGER_ID = E2.EMPLOYEE_ID
ORDER BY EMPLOYEE_ID;


-- 3. 각 직원의 급여와 그 급여가 전체 직원 급여에서 차지하는 백분율 계산
-- 출력 컬럼 : 사번, 이름, 급여, 백분율
-- 백분율은 소수점 둘째자리까지 반올림
-- 급여 없는 직원들 제외, 백분율 내림차순 정렬

SELECT EMPLOYEE_ID,
    NAME,
    SALARY,
    ROUND((SALARY / (SELECT SUM(SALARY) FROM EMPLOYEES))*100,2) PERCENT
FROM EMPLOYEES
WHERE SALARY IS NOT NULL
ORDER BY SALARY DESC;

SELECT EMPLOYEE_ID,
        NAME,
        SALARY,
        ROUND(PERCENT, 2) PERCENT
FROM (
    SELECT EMPLOYEE_ID,
        NAME,
        SALARY,
        (SALARY / (SELECT SUM(SALARY) FROM EMPLOYEES) * 100) PERCENT
    FROM EMPLOYEES
    WHERE SALARY IS NOT NULL
    ORDER BY PERCENT DESC
);

-- 4. 각 계좌의 최고 거래 금액이 높은 순으로 상위 5위까지의 계좌 출력
-- 동일 순위 존재할 경우, 각각의 순위를 모두 출력
-- 출력 컬럼 : 계좌 ID, 최고 거래 금액
SELECT *
FROM (
    SELECT T.*, DENSE_RANK() OVER(ORDER BY AMOUNT DESC) RANK
    FROM (
        SELECT ACCOUNT_ID ACCONT_ID,
            MAX(AMOUNT) AMOUNT
        FROM TRANSACTIONS
        GROUP BY ACCOUNT_ID
    ) T
)
WHERE RANK <= 5;

