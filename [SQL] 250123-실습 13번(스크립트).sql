-- 5. 각 부서에서 급여가 가장 높은 직원의 급여와 가장 낮은 직원의 급여 차이 계산
-- 부서ID로 오름차순 정렬
SELECT DISTINCT DEPARTMENT_ID,
    MAX(SALARY) OVER(PARTITION BY DEPARTMENT_ID) - MIN(SALARY) OVER(PARTITION BY DEPARTMENT_ID) DIFF_SALARY_MIN_MAX
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
ORDER BY DEPARTMENT_ID;

SELECT DISTINCT DEPARTMENT_ID,
    MAX(SALARY) - MIN(SALARY) DIFF_SALARY_MIN_MAX
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID;


-- 6. 각 직원이 속한 부서별 평균 급여와 자신의 급여를 비교하여 급여의 차이를 계산
-- 자신의 급여가 높으면 양수, 낮으면 음수
-- 출력 컬럼 : 사번, 이름, 급여, 부서 평균 급여, 급여 차이
-- 부서 평균 급여와 급여 차이는 반올림하여 정수로 표현

SELECT EMPLOYEE_ID,
    NAME,
    SALARY,
    ROUND(AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID)) AVG_DEPT_SALARY,
    ROUND(SALARY - AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID)) DIFF_SALARY
FROM EMPLOYEES;

SELECT EMPLOYEE_ID,
    NAME,
    SALARY,
    ROUND(AVG_DEPT_SALARY) AVG_DEPT_SALARY,
    ROUND(SALARY - AVG_DEPT_SALARY) DIFF_SALARY
FROM (
    SELECT EMPLOYEE_ID,
        NAME,
        SALARY,
        AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID) AVG_DEPT_SALARY
    FROM EMPLOYEES
);

