-- 10. 부서별 급여 합계, 직무별 급여 합계, 전체 급여 합계 출력
-- 부서 정보가 NULL인 행 제외
-- 부서별, 직무별로 정렬
-- 출력 컬럼 : 부서명, 직무 ID, 급여 합계
SELECT NVL((SELECT DEPARTMENT_NAME FROM DEPARTMENTS WHERE DEPARTMENT_ID = E.DEPARTMENT_ID), 'ALL DEPT') DEPT_NAME,
    NVL(JOB_ID, 'ALL JOB') JOB,
    SUM(SALARY) TOTAL_SALARY
FROM EMPLOYEES E
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY GROUPING SETS(DEPARTMENT_ID, JOB_ID, ())
ORDER BY DEPARTMENT_ID, JOB_ID;

SELECT NVL(D.DEPARTMENT_NAME, 'ALL DEPT') DEPT_NAME,
    NVL(E.JOB_ID, 'ALL JOB') JOB,
    SUM(E.SALARY) TOTAL_SALARY
FROM EMPLOYEES E, DEPARTMENTS D
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY GROUPING SETS(D.DEPARTMENT_NAME, E.JOB_ID, ())
ORDER BY D.DEPARTMENT_NAME, E.JOB_ID;

-- 11. 각 직원의 급여와 해당 직원의 부서에서 그 직원의 급여보다 100 적은 급여부터 100 큰 급여까지 해당하는 급여의 합계
-- 출력 컬럼 : 부서 ID, 사원이름, 급여, 계산한 급여
SELECT DEPARTMENT_ID,
    NAME AS EMPLOYEE_NAME,
    SALARY,
    SUM(SALARY) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY
                    RANGE BETWEEN 100 PRECEDING AND 100 FOLLOWING) SUM_OF_IN_RANGE
FROM EMPLOYEES;


-- 12. 각 직무별 평균 급여와 각 직원의 급여를 비교하여 "직무 평균 이상" 또는 "직무 평균 이하" 여부를 표시
-- 전체 평균 급여와의 비교 결과도 "전체 평균 이상" 또는 "전체 평균 이하"로 함께 표시
-- 출력 컬럼 : 사번, 급여, 직무 평균 급여 비교, 전체 평균 비교
SELECT EMPLOYEE_ID,
    SALARY,
    CASE
    WHEN AVG(SALARY) OVER() <= SALARY
        THEN '전체 평균 이상'
    ELSE'전체 평균 이하'
    END COMP_ALL,
    CASE
    WHEN AVG(SALARY) OVER(PARTITION BY JOB_ID) <= SALARY
        THEN '직무 평균 이상'
    ELSE '직무 평균 이하'
    END COMP_JOB
FROM EMPLOYEES
WHERE SALARY IS NOT NULL
ORDER BY EMPLOYEE_ID;